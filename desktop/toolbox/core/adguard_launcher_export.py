#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""Generate the AdGuard alternative launcher icon for the Android app.

Android has no API to change an installed activity's icon at runtime. The app ships one
`activity-alias` per icon style (see `AndroidManifest.xml`) and the native bridge enables exactly
one of them. This module turns the brand SVG in `assets/brand/adguard_logo.svg` into everything
those aliases need:

  * `mipmap-<density>/ic_launcher_adguard.png` (+ `_round`)  legacy bitmaps (API < 26 fallback)
  * `drawable/ic_launcher_adguard_foreground.xml`            adaptive-icon foreground vector
  * `mipmap-anydpi-v26/ic_launcher_adguard*.xml`             adaptive icons (API 26+)
  * `mipmap-anydpi/ic_launcher_adguard.xml`                  pre-26 layer-list fallback
  * `shared/assets/images/icon_adguard.png`                  in-app preview thumbnail

The brand SVG has only flat paths and no gradients/filters, so `core.vector_raster` (Pillow only)
reproduces it exactly.

Usage (from the `desktop` directory):
    python -m toolbox.core.adguard_launcher_export
    python -m toolbox.core.adguard_launcher_export --preview preview.png
"""

import os
import re
import sys

from PIL import Image

try:  # as a package module
    from . import vector_raster as vr
    from .paths import ANDROID_RES_DIR, BRAND_DIR, SHARED_DIR
except ImportError:  # run directly
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    from core import vector_raster as vr  # type: ignore[no-redef]
    from core.paths import ANDROID_RES_DIR, BRAND_DIR, SHARED_DIR

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

SVG_PATH = os.path.join(BRAND_DIR, "adguard_logo.svg")

# Legacy launcher bitmap sizes, mdpi..xxxhdpi.
ANDROID_DENSITIES = (
    ("mdpi", 48),
    ("hdpi", 72),
    ("xhdpi", 96),
    ("xxhdpi", 144),
    ("xxxhdpi", 192),
)

# The SVG's own coordinate system.
VIEW_BOX = (0.0, 0.0, 64.0, 64.0)

# Adaptive icon foreground: the 108dp layer's guaranteed-visible circle is 66dp wide centred, so a
# 64dp logo translated by 22 on each side (22..86) stays inside it under every OEM mask.
FOREGROUND_ARTBOARD = 108.0
FOREGROUND_LOGO_SIDE = 64.0
FOREGROUND_OFFSET = (FOREGROUND_ARTBOARD - FOREGROUND_LOGO_SIDE) / 2.0

_SHAPES: list | None = None


def _normalize_color(value: str) -> str:
    """Return an `#RRGGBB` colour that Android VectorDrawable accepts."""
    text = value.strip().lstrip("#")
    if len(text) == 3:
        text = "".join(char * 2 for char in text)
    elif len(text) == 4:
        text = "".join(char * 2 for char in text)
    elif len(text) == 8:
        # Drop an explicit alpha; the launcher icon is fully opaque.
        text = text[2:]
    if len(text) != 6:
        raise ValueError(f"无法解析颜色: {value}")
    return "#" + text.upper()


def load_shapes() -> list:
    """Parse the flat `<path class="stN" d="...">` shapes and their CSS fills from the SVG."""
    global _SHAPES
    if _SHAPES is not None:
        return _SHAPES
    if not os.path.exists(SVG_PATH):
        raise FileNotFoundError(f"未找到 AdGuard 图标源: {SVG_PATH}")
    with open(SVG_PATH, "r", encoding="utf-8") as handle:
        text = handle.read()

    styles = {
        name: _normalize_color(color)
        for name, color in re.findall(
            r"\.(st\d+)\s*\{[^}]*?fill\s*:\s*(#[0-9A-Fa-f]{3,8})", text
        )
    }

    shapes = []
    for match in re.finditer(r"<path\b[^>]*?/>", text, re.S):
        element = match.group(0)
        data = re.search(r'\bd="([^"]+)"', element, re.S)
        if not data:
            continue
        fill = None
        css_class = re.search(r'class="(st\d+)"', element)
        if css_class:
            fill = styles.get(css_class.group(1))
        if fill is None:
            fill_attr = re.search(r'fill="([^"]+)"', element)
            fill = _normalize_color(fill_attr.group(1)) if fill_attr else None
        if fill is None:
            continue
        path_data = re.sub(r"\s+", " ", data.group(1)).strip()
        shapes.append(vr.Shape(path_data, fill))

    if not shapes:
        raise ValueError(f"AdGuard 图标源中没有任何可渲染路径: {SVG_PATH}")
    _SHAPES = shapes
    return shapes


def render(size: int, supersample: int = 4) -> Image.Image:
    """Render the shield at `size`×`size`, filled to the square just like the source artwork."""
    return vr.render(load_shapes(), size, size, VIEW_BOX, supersample=supersample)


def foreground_vector_xml() -> str:
    """The adaptive-icon foreground as a resolution-independent VectorDrawable (108dp artboard)."""
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- AdGuard alternative launcher icon: adaptive-icon foreground.",
        "     Generated by desktop/toolbox/core/adguard_launcher_export.py from",
        "     assets/brand/adguard_logo.svg, so the launcher icon stays reproducible. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{FOREGROUND_ARTBOARD:g}dp"',
        f'    android:height="{FOREGROUND_ARTBOARD:g}dp"',
        f'    android:viewportWidth="{FOREGROUND_ARTBOARD:g}"',
        f'    android:viewportHeight="{FOREGROUND_ARTBOARD:g}">',
        f'    <group android:translateX="{FOREGROUND_OFFSET:g}" android:translateY="{FOREGROUND_OFFSET:g}">',
    ]
    for shape in load_shapes():
        lines.append(
            f'        <path android:fillColor="{shape.color}" android:pathData="{shape.path_data}" />'
        )
    lines += ["    </group>", "</vector>", ""]
    return "\n".join(lines)


def adaptive_icon_xml() -> str:
    return "\n".join(
        [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- AdGuard alternative launcher icon (API 26+ adaptive icon). -->",
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">',
            '    <background android:drawable="@color/ic_launcher_adguard_background" />',
            '    <foreground android:drawable="@drawable/ic_launcher_adguard_foreground" />',
            "</adaptive-icon>",
            "",
        ]
    )


def legacy_layer_list_xml() -> str:
    return "\n".join(
        [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Pre-API 26 fallback: the adaptive icon in mipmap-anydpi-v26 wins on 8.0+. -->",
            '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">',
            '    <item android:drawable="@color/ic_launcher_adguard_background" />',
            '    <item',
            '        android:drawable="@drawable/ic_launcher_adguard_foreground"',
            '        android:gravity="center" />',
            "</layer-list>",
            "",
        ]
    )


def _write_text(path: str, content: str, log) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    log(f"XML: {path}")
    return path


def export_all(log=print) -> list:
    res = ANDROID_RES_DIR
    files = []

    # 1. Legacy density bitmaps.
    for density, size in ANDROID_DENSITIES:
        image = render(size)
        for name in ("ic_launcher_adguard.png", "ic_launcher_adguard_round.png"):
            target = os.path.join(res, f"mipmap-{density}", name)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            image.save(target, "PNG", optimize=True)
            files.append(target)
        log(f"PNG {size}x{size}: mipmap-{density}/ic_launcher_adguard.png")

    # 2. Adaptive icon foreground + fallbacks.
    files.append(_write_text(
        os.path.join(res, "drawable", "ic_launcher_adguard_foreground.xml"),
        foreground_vector_xml(),
        log,
    ))
    for name in ("ic_launcher_adguard.xml", "ic_launcher_adguard_round.xml"):
        files.append(_write_text(
            os.path.join(res, "mipmap-anydpi-v26", name), adaptive_icon_xml(), log
        ))
    files.append(_write_text(
        os.path.join(res, "mipmap-anydpi", "ic_launcher_adguard.xml"),
        legacy_layer_list_xml(),
        log,
    ))

    # 3. In-app preview thumbnail for the appearance page.
    preview = os.path.join(SHARED_DIR, "assets", "images", "icon_adguard.png")
    os.makedirs(os.path.dirname(preview), exist_ok=True)
    render(512).save(preview, "PNG", optimize=True)
    files.append(preview)
    log(f"PNG 512x512: {preview}")

    return files


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description="导出 AdGuard 备用启动图标资源")
    parser.add_argument("--preview", default=None, help="输出一张预览图到指定路径")
    args = parser.parse_args()

    if args.preview:
        canvas = Image.new("RGBA", (512, 512), (255, 255, 255, 255))
        icon = render(512)
        canvas.alpha_composite(icon)
        canvas.save(args.preview, "PNG")
        print(f"预览已写入 {args.preview}")
        return 0

    export_all()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
