const (
	resolvConfPath   = "/etc/resolv.conf"
	resolvedDropDir  = "/etc/systemd/resolved.conf.d"
	resolvedDropFile = "/etc/systemd/resolved.conf.d/diting.conf"
)

// parseResolvConf 解析 /etc/resolv.conf 内容，提取 nameserver 列表。
//
// 仅识别 nameserver 指令，忽略 search / options / domain 与注释行。
func parseResolvConf(content string) []string {
	var servers []string
	sc := bufio.NewScanner(strings.NewReader(content))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) >= 2 && fields[0] == "nameserver" {
			servers = append(servers, fields[1])
		}
	}
	return servers
}

// renderResolvConf 生成仅含指定解析器的 resolv.conf 内容。
func renderResolvConf(servers []string) string {
	var sb strings.Builder
	sb.WriteString("# Generated by DITING. Do not edit manually.\n")
	for _, s := range servers {
		sb.WriteString("nameserver ")
		sb.WriteString(s)
		sb.WriteString("\n")
	}
	sb.WriteString("options timeout:2 attempts:2\n")
	return sb.String()
}

// readResolvConf 读取 /etc/resolv.conf 原始内容。
func readResolvConf() (string, error) {
	data, err := os.ReadFile(resolvConfPath)
	if err != nil {
		return "", err
	}
	return string(data), nil
}

// resolvConfIsSymlink 报告 /etc/resolv.conf 是否为符号链接，并返回其解析目标。
//
// 在 systemd-resolved 与 NetworkManager 环境下该文件通常为软链，
// 此时必须交由对应后端处理，直接重写会被下一次网络事件覆盖。
func resolvConfIsSymlink() (isLink bool, target string) {
	info, err := os.Lstat(resolvConfPath)
	if err != nil {
		return false, ""
	}
	if info.Mode()&os.ModeSymlink == 0 {
		return false, ""
	}
	if resolved, err := filepath.EvalSymlinks(resolvConfPath); err == nil {
		return true, resolved
	}
	return true, ""
}

// writeResolvConfAtomically 原子写入 /etc/resolv.conf（先写临时文件再重命名）。
//
// 若目标为符号链接，先解除链接并备份软链目标，避免写入穿透到系统托管文件。
func writeResolvConfAtomically(content string) error {
	if isLink, target := resolvConfIsSymlink(); isLink {
		if target != "" {
			_ = writeBackup(target, "resolv.conf")
		}
		if err := os.Remove(resolvConfPath); err != nil {
			return fmt.Errorf("解除 resolv.conf 符号链接失败: %w", err)
		}
	}

	tmp := resolvConfPath + ".diting.tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o644); err != nil {
		return fmt.Errorf("写入临时 resolv.conf 失败: %w", err)
	}
	if err := os.Rename(tmp, resolvConfPath); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("替换 resolv.conf 失败: %w", err)
	}
	return nil
}

// backupPathFor 返回指定的运行时备份文件路径，位于数据目录的 backups 子目录。
func backupPathFor(name string) string {
	return filepath.Join(platform.DefaultDataDir(), "backups", name)
}

// writeBackup 将 srcPath 当前内容备份至数据目录，便于还原与故障排查。
func writeBackup(srcPath, name string) error {
	data, err := os.ReadFile(srcPath)
	if err != nil {
		return err
	}
	path := backupPathFor(name)
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o600)
}

// runCommand 便捷封装：在给定执行器上运行命令并返回输出。
func runCommand(ctx context.Context, executor platform.CommandExecutor, name string, args ...string) (string, error) {
	if executor == nil {
		executor = platform.NewDefaultExecutor()
	}
	return executor.RunCommand(ctx, name, args...)
}
