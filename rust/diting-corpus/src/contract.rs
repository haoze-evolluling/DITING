/// The keys of one batch row, sorted: the renamed-field guard on its own.
fn row_fields() -> Vec<String> {
    let document: Value = serde_json::from_str(&batch_json(&log_rows()[..1]))
        .unwrap_or_else(|_| Value::Array(Vec::new()));
    let mut fields: Vec<String> = document
        .as_array()
        .and_then(|rows| rows.first())
        .and_then(Value::as_object)
        .map(|row| row.keys().cloned().collect())
        .unwrap_or_default();
    fields.sort();
    fields
}

/// Replays the fixture: every produced entry has to match exactly.
pub fn replay(document: &str) -> Result<usize, String> {
    let frozen: Value =
        serde_json::from_str(document).map_err(|err| format!("parse the fixture: {err}"))?;
    let now = build();
    let current: Value =
        serde_json::from_str(&now).map_err(|err| format!("parse the rebuild: {err}"))?;

    let frozen_produced = &frozen["produced"];
    let current_produced = &current["produced"];
    for key in [
        "statsFresh",
        "statsAfterTwoQueries",
        "cacheStatsFresh",
        "cacheEntryInserted",
        "cacheEntryCount",
        "cacheEntryFields",
        "resolveDomainEmpty",
        "resolveDomainNotRunning",
        "dnsLogBatch",
        "dnsLogRowFields",
    ] {
        if frozen_produced[key] != current_produced[key] {
            return Err(format!(
                "{key} changed\nfrozen: {}\nnow:    {}",
                frozen_produced[key], current_produced[key]
            ));
        }
    }
    if frozen["declared"] != current["declared"] {
        return Err(format!(
            "the declared contract changed\nfrozen: {}\nnow:    {}",
            frozen["declared"], current["declared"]
        ));
    }
    // The declared DNS row fields must agree with what the producer emits, not just with themselves.
    // The declared list is in the order the engine documents (`d`, `b`, `t`, …); the produced list is
    // sorted because it comes from a JSON object, so compare them as sets.
    let mut declared_fields = current["declared"]["dnsLogRowFields"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let mut produced_fields = current["produced"]["dnsLogRowFields"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    declared_fields.sort_by_key(|field| field.as_str().map(str::to_string));
    produced_fields.sort_by_key(|field| field.as_str().map(str::to_string));
    if declared_fields != produced_fields {
        return Err(format!(
            "the declared DNS row fields {declared_fields:?} disagree with the producer {produced_fields:?}"
        ));
    }
    Ok(10)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_batch_document_uses_the_short_field_names() {
        let document = batch_json(&log_rows());
        let rows: Value = serde_json::from_str(&document).expect("json");
        let row = rows.as_array().expect("an array")[0]
            .as_object()
            .expect("an object");
        assert_eq!(row.len(), 11);
        for field in ["d", "b", "t", "r", "a", "i", "k", "e", "c", "ts", "ttl"] {
            assert!(row.contains_key(field), "missing {field}");
        }
    }

    #[test]
    fn a_fresh_engine_reports_zero_queries() {
        let engine = Engine::new();
        let stats: Value = serde_json::from_str(&engine.stats_json()).expect("json");
        assert_eq!(stats["total"], json!(0));
        assert_eq!(stats["dropped_logs"], json!(0));
    }

    #[test]
    fn the_cache_entry_document_carries_the_kotlin_fields() {
        let engine = Engine::new();
        engine.cache().apply_policy(enabled_cache_policy());
        let query = crate::dns::query(CACHE_NAME, 1);
        let answer = crate::dns::upstream_answer(&query, &[[203, 0, 113, 7]]);
        assert!(engine.cache().put(&query, &answer));
        let entries: Value = serde_json::from_str(&engine.cache_entries_json(10)).expect("json");
        let row = entries.as_array().expect("an array")[0]
            .as_object()
            .expect("an object");
        for field in [
            "key",
            "queryName",
            "queryType",
            "queryClass",
            "createdAt",
            "expiresAt",
            "lastHitAt",
            "hitCount",
            "originalTtlSeconds",
            "responseSize",
        ] {
            assert!(row.contains_key(field), "missing {field}");
        }
    }
}
