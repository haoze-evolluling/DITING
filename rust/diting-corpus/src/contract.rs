//! The contract corpus: every JSON document Kotlin parses, frozen field by field.
//!
//! These are the documents the migration had to keep byte for byte: the Kotlin
//! readers (`EngineStats.kt`, `DnsCacheMirror.kt`, `DnsLogWriter`, `TrafficIngest`) read fixed field
//! names and silently show zeros for anything renamed. Two kinds of entry live in the fixture:
//!
//! * **produced** entries are recomputed on every replay and compared as exact strings, so renaming a
//!   field or changing an error text fails the test (`getStats`, cache stats/entries, `resolveDomain`,
//!   the DNS log batch);
//! * **declared** entries have no producer inside this crate and freeze the shape the engine and
//!   Kotlin already implement: the
//!   traffic tick (`[{"uid":..,"tx":..,"rx":..}]`, assembled by Kotlin `TrafficIngest`) and the
//!   `logHTTPEvent(flow, host, protocol, status, reason)` tuple used by the MITM relay logs.
//!
//! Timestamps are the one exception, matching the repo rule "时间相关分支靠注入时钟的单测": the cache
//! entry fixture freezes the *field names* and the count, not the clock readings inside them.

use serde_json::{json, Value};

use diting_engine::logs::batch_json;
use diting_engine::Engine;
use diting_telemetry_core::LogItem;

/// The query/answer pair used to put one entry into the cache.
const CACHE_NAME: &str = "cached.example.test";

/// Builds the whole fixture document.
pub fn build() -> String {
    json!({
        "note": "Stage 0 contract corpus: the JSON documents Kotlin parses. Produced entries are \
                 recomputed on replay; declared entries are the shape stage 3/4 must meet. \
                 Generated by `cargo run -p diting-corpus --bin gen-corpus`.",
        "produced": produced(),
        "declared": declared(),
    })
    .to_string()
}

/// A cache policy with the cache switched on: the engine starts with a disabled cache (the real
/// policy arrives in `ApplyDNSConfig`), and an empty entries document would freeze nothing.
fn enabled_cache_policy() -> diting_dns_cache_core::policy::Config {
    diting_dns_cache_core::policy::Config {
        enabled: true,
        ..diting_dns_cache_core::policy::Config::default()
    }
}

fn produced() -> Value {
    let engine = Engine::new();
    engine.cache().apply_policy(enabled_cache_policy());
    let fresh_stats = engine.stats_json();
    let fresh_cache_stats = engine.cache_stats_json();

    engine.note_query(false);
    engine.note_query(true);
    let counted_stats = engine.stats_json();

    // One cache entry, so the entries document is not empty; only the field names are frozen.
    let query = crate::dns::query(CACHE_NAME, 1);
    let answer = crate::dns::upstream_answer(&query, &[[203, 0, 113, 7]]);
    let inserted = engine.cache().put(&query, &answer);
    let entries: Value = serde_json::from_str(&engine.cache_entries_json(10))
        .unwrap_or_else(|_| Value::Array(Vec::new()));
    let entry_fields: Vec<String> = entries
        .as_array()
        .and_then(|rows| rows.first())
        .and_then(Value::as_object)
        .map(|row| row.keys().cloned().collect())
        .unwrap_or_default();

    let mut fields = entry_fields;
    fields.sort();
    let entry_count = entries.as_array().map(Vec::len).unwrap_or(0);

    json!({
        "statsFresh": fresh_stats,
        "statsAfterTwoQueries": counted_stats,
        "cacheStatsFresh": fresh_cache_stats,
        "cacheEntryInserted": inserted,
        "cacheEntryCount": entry_count,
        "cacheEntryFields": fields,
        "resolveDomainEmpty": engine.resolve_domain_blocking("", true),
        "resolveDomainNotRunning": engine.resolve_domain_blocking("example.com", true),
        "dnsLogBatch": batch_json(&log_rows()),
        "dnsLogRowFields": row_fields(),
    })
}

fn declared() -> Value {
    json!({
        "trafficTick": {
            "producer": "Kotlin TrafficIngest (delta rows from diting-telemetry-core::TrafficTracker)",
            "shape": "[{\"uid\":<int>,\"tx\":<long>,\"rx\":<long>}]",
            "fields": ["uid", "tx", "rx"]
        },
        "httpEvent": {
            "producer": "the MITM relay (logHTTPEvent)",
            "fields": ["host", "protocol", "status", "reason"],
            "protocols": ["HTTPS", "HTTP/1.1"],
            "statuses": [
                "allowed", "blocked", "passthrough", "rewritten", "error",
                "handshake_failed", "upstream_failed"
            ]
        },
        "batchLogSignature": "(Ljava/lang/String;)V",
        "raceLogArguments": 13,
        "bootstrapLogArguments": 8,
        "dnsLogRowFields": ["d", "b", "t", "r", "a", "i", "k", "e", "c", "ts", "ttl"],
    })
}

