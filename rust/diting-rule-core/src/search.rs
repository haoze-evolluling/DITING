//! Rule-list search: one lowercased index per rule table, scanned per keystroke.
//!
//! The rules page filters a whole table on every keystroke (`filteredRulesProvider`), which is
//! `pattern.toLowerCase().contains(query) || target.toLowerCase().contains(query)` over up to a
//! subscription-sized table: 25-35 ms per key on the UI isolate for 100k rows, and the lowercasing
//! is redone from scratch every time. Folding the rows once when the table changes and scanning
//! them natively turns the per-keystroke cost into memory bandwidth.
//!
//! # Case folding has to match Dart exactly
//!
//! The rules page shows the rows this index returns, so [`fold`] has to reproduce the fold the
//! page used before the move: a port of `String.toLowerCase`, not `str::to_lowercase`:
//!
//! * Dart's conversion is context free: `'ΑΣ'.toLowerCase()` is `ασ`, while `str::to_lowercase`
//!   applies the Unicode final-sigma rule and returns `ας`. Folding per `char` avoids that.
//! * `U+0130` (İ) lowercases to `i` + combining dot in Unicode; Dart drops the dot and returns
//!   `i`. Pinned as an explicit case.
//! * Dart's case tables predate several case pairs, so it leaves the code points listed in
//!   [`DART_UNMAPPED`] untouched while Rust lowercases them. That list was generated by sweeping
//!   every code point through `String.toLowerCase` on Dart, folding it in Rust and diffing the
//!   results.

