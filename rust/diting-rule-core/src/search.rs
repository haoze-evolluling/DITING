/// Lowercases `text` the way `String.toLowerCase` does in Dart.
pub fn fold(text: &str) -> Cow<'_, str> {
    if text.is_ascii() {
        // Subscription-sized tables are almost entirely ASCII; skip the char walk there.
        if !text.bytes().any(|byte| byte.is_ascii_uppercase()) {
            return Cow::Borrowed(text);
        }
        return Cow::Owned(text.to_ascii_lowercase());
    }
    let mut folded = String::with_capacity(text.len());
    for character in text.chars() {
        if character == '\u{130}' {
            // Dart returns `i`, Unicode (and `char::to_lowercase`) returns `i` + U+0307.
            folded.push('i');
        } else if dart_leaves_unmapped(character) {
            folded.push(character);
        } else {
            folded.extend(character.to_lowercase());
        }
    }
    Cow::Owned(folded)
}

fn dart_leaves_unmapped(character: char) -> bool {
    let code = character as u32;
    DART_UNMAPPED
        .binary_search_by(|&(start, end)| {
            if code < start {
                std::cmp::Ordering::Greater
            } else if code > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// One searchable row: a pattern span and its optional target span, both into
/// [`RuleSearchIndex::text`].
#[derive(Debug)]
struct Row {
    pattern: Span,
    target: Option<Span>,
}

/// Half-open byte range into the folded text arena.
#[derive(Debug, Clone, Copy)]
struct Span {
    start: u32,
    len: u32,
}

/// A searchable rule table. Built once per table snapshot, queried once per keystroke.
///
/// Folded text lives in one arena instead of a `String` per field: a 100k-row table is ~200k
/// fields, and the scan reads them in order, so one contiguous buffer both builds and scans faster
/// than 200k separate allocations.
#[derive(Debug, Default)]
pub struct RuleSearchIndex {
    text: String,
    rows: Vec<Row>,
}

impl RuleSearchIndex {
    /// Reserves space for `rows` entries; a malformed payload must not ask for more than it holds,
    /// which is the caller's check.
    pub fn with_capacity(rows: usize) -> Self {
        Self {
            text: String::new(),
            rows: Vec::with_capacity(rows),
        }
    }

    /// Folds and stores one row. `target` is `None` for rule kinds that have no target column.
    pub fn push(&mut self, pattern: &str, target: Option<&str>) {
        let pattern = self.store(pattern);
        let target = target.map(|text| self.store(text));
        self.rows.push(Row { pattern, target });
    }

    pub fn len(&self) -> usize {
        self.rows.len()
    }

    pub fn is_empty(&self) -> bool {
        self.rows.is_empty()
    }

    /// Indices of the rows whose pattern or target contains `needle`, ascending.
    ///
    /// `needle` is folded here, so the caller can hand over the search box text as typed. An empty
    /// needle matches every row, exactly like `String.contains('')`.
    pub fn matching(&self, needle: &str) -> Vec<u32> {
        let needle = fold(needle);
        let needle: &str = &needle;
        let mut hits = Vec::new();
        for (index, row) in self.rows.iter().enumerate() {
            let hit = self.text_of(row.pattern).contains(needle)
                || row
                    .target
                    .is_some_and(|span| self.text_of(span).contains(needle));
            if hit {
                hits.push(index as u32);
            }
        }
        hits
    }

    fn store(&mut self, text: &str) -> Span {
        let start = self.text.len() as u32;
        self.text.push_str(&fold(text));
        Span {
            start,
            len: self.text.len() as u32 - start,
        }
    }

    fn text_of(&self, span: Span) -> &str {
        let start = span.start as usize;
        &self.text[start..start + span.len as usize]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hits(index: &RuleSearchIndex, needle: &str) -> Vec<u32> {
        index.matching(needle)
    }

    #[test]
    fn matches_patterns_and_targets_in_table_order() {
        let mut index = RuleSearchIndex::default();
        index.push("||ads.example.com^", None);
        index.push("||tracker.example.net^", Some("0.0.0.1"));
        index.push("||safe.example.org^", Some("1.1.1.1"));

        assert_eq!(hits(&index, "example"), vec![0, 1, 2]);
        assert_eq!(hits(&index, "EXAMPLE"), vec![0, 1, 2]);
        assert_eq!(hits(&index, "ads"), vec![0]);
        // `0.0.0.1` only lives in the target column.
        assert_eq!(hits(&index, "0.0.0.1"), vec![1]);
        assert_eq!(hits(&index, "nothing"), Vec::<u32>::new());
        // `contains('')` is true for every row in Dart too.
        assert_eq!(hits(&index, ""), vec![0, 1, 2]);
    }

    #[test]
    fn fold_matches_dart_for_the_awkward_cases() {
        // Dart: context free, so no final sigma.
        assert_eq!(fold("ΑΣ"), "ασ");
        assert_eq!(fold("Σ"), "σ");
        // Dart: İ loses the combining dot.
        assert_eq!(fold("İ"), "i");
        // Both agree on the ordinary mappings.
        assert_eq!(fold("ẞ"), "ß");
        assert_eq!(fold("ǅ"), "ǆ");
        assert_eq!(fold("Ⅰ"), "ⅰ");
        // Dart's tables have no mapping for these, so neither may fold them.
        assert_eq!(fold("\u{104B0}"), "\u{104B0}");
        assert_eq!(fold("\u{13A0}"), "\u{13A0}");
        // ASCII goes through the borrowed fast path.
        assert_eq!(fold("ADs"), "ads");
        assert!(matches!(fold("already"), Cow::Borrowed(_)));
    }

    #[test]
    fn fold_handles_non_ascii_needles() {
        let mut index = RuleSearchIndex::default();
        index.push("||ÄPFEL.example.com^", None);
        index.push("||ähnlich.example.com^", None);
        assert_eq!(hits(&index, "ÄPFEL"), vec![0]);
        assert_eq!(hits(&index, "ähn"), vec![1]);
        assert_eq!(hits(&index, "ÄHN"), vec![1]);
    }

    #[test]
    fn unmapped_table_is_sorted_and_disjoint() {
        for pair in DART_UNMAPPED.windows(2) {
            assert!(
                pair[0].1 < pair[1].0,
                "{:x?} overlaps {:x?}",
                pair[0],
                pair[1]
            );
        }
    }

    #[test]
    fn empty_index_matches_nothing() {
        let index = RuleSearchIndex::default();
        assert!(index.is_empty());
        assert_eq!(hits(&index, "ads"), Vec::<u32>::new());
    }
}
