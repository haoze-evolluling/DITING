//! The connection-log deduplication kernel of the Android tunnel engine.
//!
//! The engine logs one line per flow tuple. `connLogSeen` used to be a Go `map[string]struct{}`
//! that re-allocated the whole key for every flow, including the duplicates it then dropped, and
//! reset wholesale once it reached 8192 entries. This crate owns that set and the key builder:
//!
//! * `build_key` reproduces `connLogKey` byte for byte (`prefix + app + '|' + dest + '|' + port +
//!   '|' + protocol` and, when a reason is present, `'|' + reason`);
//! * `ConnLogDedup::mark` returns "already seen" or inserts, clearing the set first when it is
//!   full (a stale key only costs one duplicate log line);
//! * `reset` (a new full-tunnel session) empties the set without touching the overflow counter.
//!
//! There is no clock, no I/O and no logging here. The corpus in `tests/fixtures` was generated by
//! the old Go `connLogKey` / `connLogSeenDedup`. If the Go side cannot load the library it stops
//! deduplicating (every flow is logged) rather than keeping a second implementation.

pub mod dedup;
pub mod ffi;
pub mod key;
pub mod payload;

pub use dedup::ConnLogDedup;
pub use key::build_key;
