use std::path::{Path, PathBuf};

const SKIPPED_EXTENSIONS: &[&str] = &["map"];

fn collect(root: &Path, current: &Path, files: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = std::fs::read_dir(current) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, files);
            continue;
        }
        let extension = path
            .extension()
            .and_then(|value| value.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        if SKIPPED_EXTENSIONS.contains(&extension.as_str()) {
            continue;
        }
        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };
        let name = relative
            .components()
            .map(|component| component.as_os_str().to_string_lossy())
            .collect::<Vec<_>>()
            .join("/");
        files.push((name, path));
    }
}

fn locate_dist() -> PathBuf {
    if let Some(custom) = std::env::var_os("DITING_UI_DIST").filter(|value| !value.is_empty()) {
        return PathBuf::from(custom);
    }
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    manifest
        .parent()
        .and_then(Path::parent)
        .map(|root| root.join("desktop").join("ui").join("dist"))
        .unwrap_or_else(|| manifest.join("dist"))
}

fn main() {
    let dist = locate_dist();
    println!("cargo:rerun-if-env-changed=DITING_UI_DIST");
    println!("cargo:rerun-if-changed={}", dist.display());

    let mut source = String::from("// Generated by build.rs; do not edit.\n");
    let mut files = Vec::new();
    if dist.is_dir() {
        collect(&dist, &dist, &mut files);
    }
    files.sort_by(|left, right| left.0.cmp(&right.0));

    if files.is_empty() {
        source.push_str("pub const HAS_ASSETS: bool = false;\n");
        source.push_str("pub static ASSETS: &[(&str, &[u8])] = &[];\n");
    } else {
        source.push_str("pub const HAS_ASSETS: bool = true;\n");
        source.push_str("pub static ASSETS: &[(&str, &[u8])] = &[\n");
        for (name, path) in &files {
            source.push_str(&format!("    ({name:?}, include_bytes!({path:?})),\n"));
        }
        source.push_str("];\n");
    }

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("dist_assets.rs");
    std::fs::write(&out, source).expect("write embedded asset table");
}
