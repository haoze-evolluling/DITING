use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let dist = manifest
        .join("..")
        .join("..")
        .join("desktop")
        .join("service")
        .join("frontend")
        .join("dist");
    println!("cargo:rerun-if-changed={}", dist.display());

    let mut files = Vec::new();
    if dist.is_dir() {
        collect(&dist, &dist, &mut files);
        files.sort_by(|left, right| left.0.cmp(&right.0));
    }

    let has_assets = files.iter().any(|(name, _)| name == "index.html");
    let mut source = String::new();
    source.push_str("// Generated by build.rs; do not edit.\n");
    source.push_str(&format!("pub const HAS_ASSETS: bool = {has_assets};\n"));
    source.push_str("pub static ASSETS: &[(&str, &[u8])] = &[\n");
    for (name, path) in files {
        source.push_str(&format!(
            "    ({:?}, include_bytes!({:?})),\n",
            name,
            path.to_string_lossy()
        ));
    }
    source.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("dist_assets.rs");
    std::fs::write(&out, source).expect("write embedded asset table");
}

fn collect(root: &Path, directory: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = std::fs::read_dir(directory) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.is_file() {
            if let Ok(relative) = path.strip_prefix(root) {
                let name = relative
                    .components()
                    .map(|component| component.as_os_str().to_string_lossy().into_owned())
                    .collect::<Vec<_>>()
                    .join("/");
                out.push((name, path));
            }
        }
    }
}
