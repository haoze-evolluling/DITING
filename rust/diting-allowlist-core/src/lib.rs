//! The strict app-allowlist authorization kernel of the Android tunnel engine.
//!
//! This is the whole of `android/engine/engine_app_allowlist.go` after migration: the per-UID
//! allowed-domain sets (with Go's Unicode-lowercase / trim / one-trailing-dot normalization), the
//! suffix walk that decides whether a query may resolve, the per-UID IP grants that follow a DNS
//! answer's TTL, the "netd query" fan-out (a positive answer grants every UID whose allowlist
//! matches the question), and the 256-entry pruning.
//!
//! Go keeps the JSON config, the `dns.Msg` traversal (A/AAAA bytes + TTL) and the `net.IP`
//! loopback fast path. Time is injected (`now_ns`), so grants and expiry can be replayed exactly;
//! see `tests/fixtures/domain_matches.tsv`, generated by the old Go `domainMatches`.
//!
//! The kernel never logs. When the library is missing the Go wrapper treats a configured allowlist
//! as fail-closed (DNS and connections are denied) rather than silently allowing everything.

pub mod domain;
pub mod engine;
pub mod ffi;
pub mod payload;

pub use domain::{domain_matches, normalize_entry, normalize_query_name};
pub use engine::AllowlistKernel;
