//! The IP → domain LRU cache of the Android tunnel engine.
//!
//! The engine remembers which domain resolved to which address so a direct-IP flow can still be
//! labelled with a hostname. This crate is the whole of `android/engine/ip_domain_cache.go` after
//! migration:
//!
//! * `put` updates an existing key in place and moves it to the most-recently-written position; a
//!   new key at capacity evicts the least-recently-written one;
//! * `get` never promotes — only `put` touches the order, exactly like the Go `container/list`
//!   implementation that moved an element only inside `put`;
//! * empty IPs and empty domains are ignored on both sides, and a non-positive capacity means the
//!   default 2048.
//!
//! Ordering uses a monotonically increasing stamp (`u128`, so it cannot realistically wrap) and a
//! `BTreeMap<stamp, ip>`: the smallest stamp is the eviction candidate. That reproduces
//! `MoveToFront` / `Back()` with `O(log n)` operations and no unsafe linked list.
//!
//! There is no clock, no I/O and no logging. The corpus in `tests/fixtures/lru_trace.tsv` was
//! generated by the old Go implementation. A missing library disables the hints (every lookup
//! misses), which only costs the hostname label of direct-IP flows.

