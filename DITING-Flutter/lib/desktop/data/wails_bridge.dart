import 'dart:js_interop';
import 'dart:js_interop_unsafe';

import 'package:diting/desktop/data/desktop_backend.dart';
import 'package:diting/desktop/data/desktop_models.dart';
import 'package:diting/desktop/data/desktop_native_bridge.dart';

DesktopNativeBridge createDesktopNativeBridge() => WailsDesktopNativeBridge();

@JS('go.main.App.GetPlatform')
external JSPromise<JSString>? _getPlatform();
@JS('go.main.App.GetCoreServiceStatus')
external JSPromise<JSObject>? _getCoreServiceStatus();
@JS('go.main.App.IsAutoStartEnabled')
external JSPromise<JSBoolean>? _isAutoStartEnabled();
@JS('go.main.App.SetAutoStart')
external JSPromise<JSBoolean>? _setAutoStart(JSBoolean enabled);
@JS('go.main.App.StartCoreService')
external JSPromise<JSString>? _startCoreService();
@JS('go.main.App.StopCoreService')
external JSPromise<JSString>? _stopCoreService();
@JS('go.main.App.RestartCoreService')
external JSPromise<JSString>? _restartCoreService();
@JS('go.main.App.InstallAndStartCoreService')
external JSPromise<JSString>? _installAndStartCoreService();
@JS('go.main.App.RunEmergencyRestore')
external JSPromise<JSString>? _runEmergencyRestore();

/// Thin JS-interop adapter over the bindings already generated by Wails.
class WailsDesktopNativeBridge implements DesktopNativeBridge {
  @override
  bool get isAvailable => globalContext.has('go');

  @override
  Future<String> getPlatform() => _stringCall(() => _getPlatform());

  @override
  Future<CoreServiceStatus> getCoreServiceStatus() async {
    final promise = _getCoreServiceStatus();
    if (promise == null) {
      throw const DesktopBackendException('Wails 服务状态桥接不可用。');
    }
    final result = await promise.toDart;
    final value = result.dartify();
    if (value is! Map) {
      throw const DesktopBackendException('核心服务状态格式不正确。');
    }
    return CoreServiceStatus.fromJson(Map<String, dynamic>.from(value));
  }

  @override
  Future<bool> isAutoStartEnabled() async {
    final promise = _isAutoStartEnabled();
    if (promise == null) {
      throw const DesktopBackendException('Wails 自启动桥接不可用。');
    }
    return (await promise.toDart).toDart;
  }

  @override
  Future<bool> setAutoStart(bool enabled) async {
    final promise = _setAutoStart(enabled.toJS);
    if (promise == null) {
      throw const DesktopBackendException('Wails 自启动桥接不可用。');
    }
    return (await promise.toDart).toDart;
  }

  @override
  Future<String> startCoreService() => _stringCall(() => _startCoreService());

  @override
  Future<String> stopCoreService() => _stringCall(() => _stopCoreService());

  @override
  Future<String> restartCoreService() =>
      _stringCall(() => _restartCoreService());

  @override
  Future<String> installAndStartCoreService() =>
      _stringCall(() => _installAndStartCoreService());

  @override
  Future<String> runEmergencyRestore() =>
      _stringCall(() => _runEmergencyRestore());

  Future<String> _stringCall(JSPromise<JSString>? Function() call) async {
    final promise = call();
    if (promise == null) {
      throw const DesktopBackendException('Wails 原生桥接不可用。');
    }
    try {
      return (await promise.toDart).toDart;
    } on Object catch (error) {
      throw DesktopBackendException(error.toString());
    }
  }
}
